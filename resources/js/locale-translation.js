function isEnglishLocale() {
    const locale = (document.documentElement.lang || document.documentElement.getAttribute('lang') || '').toLowerCase();
    return locale === 'en' || locale.startsWith('en-');
}

function shouldUseEnglishInputMode() {
    const root = document.documentElement;
    return root.getAttribute('data-input-language') === 'english';
}

function applyEnglishInputMode(root) {
    if (!shouldUseEnglishInputMode() || !root) {
        return;
    }

    const controls = root.querySelectorAll('input, textarea, select');
    controls.forEach((element) => {
        if (element.matches('[type="hidden"], [type="checkbox"], [type="radio"], [type="file"], [type="submit"], [type="button"], [type="reset"], [type="image"], [type="color"]')) {
            return;
        }

        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            if (!element.hasAttribute('dir')) {
                element.setAttribute('dir', 'ltr');
            }
            if (!element.hasAttribute('lang')) {
                element.setAttribute('lang', 'en');
            }
            if (!element.hasAttribute('inputmode')) {
                element.setAttribute('inputmode', 'latin');
            }
            if (!element.hasAttribute('spellcheck')) {
                element.setAttribute('spellcheck', 'false');
            }
        }

        if (element.tagName === 'SELECT' && !element.hasAttribute('dir')) {
            element.setAttribute('dir', 'ltr');
        }
    });
}

function translateText(text) {
    if (!text) return text;

    let translated = text;
    Object.entries(translationMap).forEach(([from, to]) => {
        translated = translated.replaceAll(from, to);
    });

    return translated;
}

function translateNode(node) {
    if (!node) return;

    if (node.nodeType === Node.TEXT_NODE) {
        const updated = translateText(node.nodeValue || '');
        if (updated !== node.nodeValue) {
            node.nodeValue = updated;
        }
    } else if (node.nodeType === Node.ELEMENT_NODE) {
        if (['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(node.tagName)) {
            return;
        }

        ['placeholder', 'title', 'aria-label', 'alt'].forEach((attr) => {
            if (node.hasAttribute(attr)) {
                const value = node.getAttribute(attr);
                const translated = translateText(value || '');
                if (translated !== value) {
                    node.setAttribute(attr, translated);
                }
            }
        });
    }
}

function translateSubtree(root) {
    if (!root) return;

    if (root.nodeType === Node.TEXT_NODE) {
        translateNode(root);
        return;
    }

    if (root.nodeType !== Node.ELEMENT_NODE) {
        return;
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: (textNode) => {
            const parent = textNode.parentElement;
            if (!parent) return NodeFilter.FILTER_REJECT;
            if (['SCRIPT', 'STYLE', 'CODE', 'PRE'].includes(parent.tagName)) {
                return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
        },
    });

    while (walker.nextNode()) {
        translateNode(walker.currentNode);
    }

    Array.from(root.querySelectorAll('*')).forEach((element) => {
        ['placeholder', 'title', 'aria-label', 'alt'].forEach((attr) => {
            if (element.hasAttribute(attr)) {
                const value = element.getAttribute(attr);
                const translated = translateText(value || '');
                if (translated !== value) {
                    element.setAttribute(attr, translated);
                }
            }
        });
    });
}

function applyTranslations() {
    if (!isEnglishLocale()) {
        return;
    }

    const title = translateText(document.title || '');
    if (title !== document.title) {
        document.title = title;
    }

    translateSubtree(document.body || document.documentElement);
}

function applyLocaleBehaviors() {
    applyTranslations();
    applyEnglishInputMode(document.body || document.documentElement);
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyLocaleBehaviors, { once: true });
} else {
    applyLocaleBehaviors();
}

const observer = new MutationObserver(() => {
    if (isEnglishLocale()) {
        applyTranslations();
    }

    applyEnglishInputMode(document.body || document.documentElement);
});

if (document.body) {
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
